-- Compras y egresos: primera capa de datos.
-- IMPORTANTE: crear esta migración en desarrollo y probarla antes de aplicarla.
-- No carga CUIT, sucursales ni registros automáticamente: esos datos deben mapearse explícitamente.

BEGIN;

-- El CUIT se deja nullable para no bloquear los registros legales existentes.
ALTER TABLE public.empresas
  ADD COLUMN IF NOT EXISTS cuit text;

CREATE UNIQUE INDEX IF NOT EXISTS empresas_cuit_unique
  ON public.empresas (cuit)
  WHERE cuit IS NOT NULL AND btrim(cuit) <> '';

-- Compatibilidad: unidades_negocio ya existe en desarrollo y se relaciona
-- con empresas mediante empresa_unidad_negocio. No se cambia su estructura.
CREATE TABLE IF NOT EXISTS public.unidades_negocio (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre text NOT NULL UNIQUE,
  tipo text,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.empresa_unidad_negocio (
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
  unidad_negocio_id uuid NOT NULL REFERENCES public.unidades_negocio(id) ON DELETE CASCADE,
  activo boolean NOT NULL DEFAULT true,
  fecha_desde date NOT NULL DEFAULT CURRENT_DATE,
  fecha_hasta date,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (empresa_id, unidad_negocio_id),
  CONSTRAINT empresa_unidad_negocio_fechas_check
    CHECK (fecha_hasta IS NULL OR fecha_hasta >= fecha_desde)
);

-- Solicitudes internas: todavía no representan una compra comprometida.
CREATE TABLE IF NOT EXISTS public.solicitudes_compra (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE RESTRICT,
  unidad_negocio_id uuid NOT NULL,
  numero bigint GENERATED BY DEFAULT AS IDENTITY,
  estado text NOT NULL DEFAULT 'borrador',
  justificacion text,
  fecha_necesaria date,
  solicitante_id uuid REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  aprobado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  aprobado_at timestamptz,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT solicitudes_compra_unidad_empresa_fk
    FOREIGN KEY (empresa_id, unidad_negocio_id)
    REFERENCES public.empresa_unidad_negocio(empresa_id, unidad_negocio_id) ON DELETE RESTRICT,
  CONSTRAINT solicitudes_compra_estado_check
    CHECK (estado IN ('borrador','pendiente','aprobada','rechazada','ordenada','cancelada')),
  CONSTRAINT solicitudes_compra_numero_empresa_unique UNIQUE (empresa_id, numero)
);

CREATE TABLE IF NOT EXISTS public.solicitud_compra_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  solicitud_id uuid NOT NULL REFERENCES public.solicitudes_compra(id) ON DELETE CASCADE,
  producto_id uuid REFERENCES public.productos(id) ON DELETE SET NULL,
  descripcion text NOT NULL,
  cantidad numeric(14,3) NOT NULL,
  unidad_medida text,
  precio_estimado numeric(14,2),
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT solicitud_compra_items_cantidad_check CHECK (cantidad > 0),
  CONSTRAINT solicitud_compra_items_precio_check CHECK (precio_estimado IS NULL OR precio_estimado >= 0),
  CONSTRAINT solicitud_compra_items_descripcion_check CHECK (btrim(descripcion) <> '')
);

-- Orden formal al proveedor. La solicitud de origen es opcional para compras excepcionales.
CREATE TABLE IF NOT EXISTS public.ordenes_compra (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE RESTRICT,
  unidad_negocio_id uuid NOT NULL,
  solicitud_id uuid REFERENCES public.solicitudes_compra(id) ON DELETE SET NULL,
  proveedor_id uuid NOT NULL REFERENCES public.proveedores(id) ON DELETE RESTRICT,
  numero bigint GENERATED BY DEFAULT AS IDENTITY,
  fecha date NOT NULL DEFAULT CURRENT_DATE,
  fecha_entrega_estimada date,
  estado text NOT NULL DEFAULT 'borrador',
  condicion_pago text,
  subtotal numeric(14,2) NOT NULL DEFAULT 0,
  descuentos numeric(14,2) NOT NULL DEFAULT 0,
  impuestos numeric(14,2) NOT NULL DEFAULT 0,
  total numeric(14,2) NOT NULL DEFAULT 0,
  notas text,
  creado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  aprobado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  aprobado_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ordenes_compra_unidad_empresa_fk
    FOREIGN KEY (unidad_negocio_id, empresa_id)
    REFERENCES public.unidades_negocio(id, empresa_id) ON DELETE RESTRICT,
  CONSTRAINT ordenes_compra_estado_check
    CHECK (estado IN ('borrador','pendiente_aprobacion','aprobada','enviada','parcialmente_recibida','recibida','cerrada','cancelada')),
  CONSTRAINT ordenes_compra_importes_check
    CHECK (subtotal >= 0 AND descuentos >= 0 AND impuestos >= 0 AND total >= 0),
  CONSTRAINT ordenes_compra_numero_empresa_unique UNIQUE (empresa_id, numero)
);

CREATE TABLE IF NOT EXISTS public.orden_compra_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  orden_compra_id uuid NOT NULL REFERENCES public.ordenes_compra(id) ON DELETE CASCADE,
  producto_id uuid REFERENCES public.productos(id) ON DELETE SET NULL,
  descripcion text NOT NULL,
  cantidad numeric(14,3) NOT NULL,
  unidad_medida text,
  precio_unitario numeric(14,2) NOT NULL DEFAULT 0,
  alicuota_iva numeric(5,2) NOT NULL DEFAULT 0,
  descuento numeric(14,2) NOT NULL DEFAULT 0,
  total_linea numeric(14,2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT orden_compra_items_cantidad_check CHECK (cantidad > 0),
  CONSTRAINT orden_compra_items_importes_check
    CHECK (precio_unitario >= 0 AND alicuota_iva >= 0 AND descuento >= 0 AND total_linea >= 0),
  CONSTRAINT orden_compra_items_descripcion_check CHECK (btrim(descripcion) <> '')
);

-- Recepciones separadas de la orden: permite recibir mercadería en más de una entrega.
CREATE TABLE IF NOT EXISTS public.recepciones_compra (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  orden_compra_id uuid NOT NULL REFERENCES public.ordenes_compra(id) ON DELETE RESTRICT,
  fecha_recepcion timestamptz NOT NULL DEFAULT now(),
  recibido_por uuid REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  estado text NOT NULL DEFAULT 'confirmada',
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recepciones_compra_estado_check CHECK (estado IN ('borrador','confirmada','anulada'))
);

CREATE TABLE IF NOT EXISTS public.recepcion_compra_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  recepcion_id uuid NOT NULL REFERENCES public.recepciones_compra(id) ON DELETE CASCADE,
  orden_compra_item_id uuid NOT NULL REFERENCES public.orden_compra_items(id) ON DELETE RESTRICT,
  cantidad_recibida numeric(14,3) NOT NULL,
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recepcion_compra_items_cantidad_check CHECK (cantidad_recibida > 0)
);

-- Gastos que no necesariamente nacen de una factura de mercadería:
-- servicios, impuestos, alquileres y otros compromisos.
CREATE TABLE IF NOT EXISTS public.gastos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE RESTRICT,
  unidad_negocio_id uuid,
  proveedor_id uuid REFERENCES public.proveedores(id) ON DELETE SET NULL,
  categoria text NOT NULL,
  descripcion text NOT NULL,
  fecha_emision date NOT NULL DEFAULT CURRENT_DATE,
  fecha_vencimiento date,
  importe numeric(14,2) NOT NULL,
  estado text NOT NULL DEFAULT 'pendiente',
  recurrente boolean NOT NULL DEFAULT false,
  frecuencia text,
  comprobante_url text,
  observaciones text,
  creado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT gastos_unidad_empresa_fk
    FOREIGN KEY (unidad_negocio_id, empresa_id)
    REFERENCES public.unidades_negocio(id, empresa_id) ON DELETE RESTRICT,
  CONSTRAINT gastos_importe_check CHECK (importe >= 0),
  CONSTRAINT gastos_estado_check CHECK (estado IN ('pendiente','parcial','pagado','vencido','anulado')),
  CONSTRAINT gastos_frecuencia_check
    CHECK (frecuencia IS NULL OR frecuencia IN ('semanal','mensual','bimestral','trimestral','semestral','anual')),
  CONSTRAINT gastos_descripcion_no_vacia CHECK (btrim(descripcion) <> ''),
  CONSTRAINT gastos_categoria_no_vacia CHECK (btrim(categoria) <> '')
);

-- Pagos asociados a gastos no facturados; se mantienen separados de pagos de facturas
-- hasta revisar y armonizar el modelo actual de pagos y sus políticas RLS.
CREATE TABLE IF NOT EXISTS public.gastos_pagos (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  gasto_id uuid NOT NULL REFERENCES public.gastos(id) ON DELETE RESTRICT,
  fecha date NOT NULL DEFAULT CURRENT_DATE,
  monto numeric(14,2) NOT NULL,
  forma_pago_id uuid REFERENCES public.formas_pago(id) ON DELETE SET NULL,
  referencia text,
  comprobante_url text,
  registrado_por uuid REFERENCES auth.users(id) ON DELETE SET NULL DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT gastos_pagos_monto_check CHECK (monto > 0)
);

-- Distribución analítica de un gasto compartido: no duplica la obligación ni el pago.
CREATE TABLE IF NOT EXISTS public.gastos_distribuciones (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  gasto_id uuid NOT NULL REFERENCES public.gastos(id) ON DELETE CASCADE,
  empresa_id uuid NOT NULL REFERENCES public.empresas(id) ON DELETE RESTRICT,
  unidad_negocio_id uuid NOT NULL,
  importe numeric(14,2) NOT NULL,
  porcentaje numeric(7,4),
  observaciones text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT gastos_distribuciones_importe_check CHECK (importe > 0),
  CONSTRAINT gastos_distribuciones_porcentaje_check
    CHECK (porcentaje IS NULL OR (porcentaje > 0 AND porcentaje <= 100)),
  CONSTRAINT gastos_distribuciones_gasto_unidad_unique
    UNIQUE (gasto_id, empresa_id, unidad_negocio_id),
  CONSTRAINT gastos_distribuciones_unidad_empresa_fk
    FOREIGN KEY (empresa_id, unidad_negocio_id)
    REFERENCES public.empresa_unidad_negocio(empresa_id, unidad_negocio_id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS solicitudes_compra_empresa_estado_idx
  ON public.solicitudes_compra (empresa_id, estado, created_at DESC);
CREATE INDEX IF NOT EXISTS ordenes_compra_empresa_estado_fecha_idx
  ON public.ordenes_compra (empresa_id, estado, fecha DESC);
CREATE INDEX IF NOT EXISTS ordenes_compra_proveedor_fecha_idx
  ON public.ordenes_compra (proveedor_id, fecha DESC);
CREATE INDEX IF NOT EXISTS recepciones_compra_orden_fecha_idx
  ON public.recepciones_compra (orden_compra_id, fecha_recepcion DESC);
CREATE INDEX IF NOT EXISTS gastos_empresa_estado_vencimiento_idx
  ON public.gastos (empresa_id, estado, fecha_vencimiento);
CREATE INDEX IF NOT EXISTS gastos_pagos_gasto_fecha_idx
  ON public.gastos_pagos (gasto_id, fecha DESC);
CREATE INDEX IF NOT EXISTS gastos_distribuciones_gasto_idx
  ON public.gastos_distribuciones (gasto_id);

